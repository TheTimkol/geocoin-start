    private static Dictionary<string, string> AdditionalMap(string language)
        => language switch { "zh-CN" => AdditionalChinese, "pt-BR" => AdditionalPortuguese, "it" => AdditionalItalian, _ => new Dictionary<string, string>() };

    private static Dictionary<string, string> AdditionalReverseMap(string language)
        => language switch { "zh-CN" => AdditionalChineseReverse.Value, "pt-BR" => AdditionalPortugueseReverse.Value, "it" => AdditionalItalianReverse.Value, _ => new Dictionary<string, string>() };

    public static bool TryNormalizeEnglishToRussian(string value, out string russian)
    {
        if (AdditionalEnglishReverse.Value.TryGetValue(value, out russian!)) return true;
        foreach (var pair in AdditionalRussianToEnglish.Where(pair => pair.Value.EndsWith(" ", StringComparison.Ordinal)).OrderByDescending(pair => pair.Value.Length))
        {
            if (!value.StartsWith(pair.Value, StringComparison.Ordinal)) continue;
            russian = pair.Key + value[pair.Value.Length..];
            return true;
        }
        russian = value;
        return false;
    }
