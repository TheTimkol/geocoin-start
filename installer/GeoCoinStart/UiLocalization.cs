    private static readonly Dictionary<string, string> ChineseReverse = Reverse(Chinese);
    private static readonly Dictionary<string, string> PortugueseReverse = Reverse(Portuguese);
    private static readonly Dictionary<string, string> ItalianReverse = Reverse(Italian);

    public static string NormalizeLanguage(string? language)
        => LanguageCodes.FirstOrDefault(code => string.Equals(code, language, StringComparison.OrdinalIgnoreCase)) ?? "ru";

    public static string DisplayName(string? language)
    {
        int index = Array.IndexOf(LanguageCodes, NormalizeLanguage(language));
        return LanguageNames[index < 0 ? 0 : index];
    }

    public static CultureInfo Culture(string? language)
        => CultureInfo.GetCultureInfo(NormalizeLanguage(language) switch { "zh-CN" => "zh-CN", "pt-BR" => "pt-BR", "it" => "it-IT", "en" => "en-US", _ => "ru-RU" });

    public static string TranslateFromEnglish(string language, string value)
    {
        string code = NormalizeLanguage(language);
        Dictionary<string, string> map = Map(code);
        string translated = TranslateUsingMap(value, map);
        if (string.Equals(translated, value, StringComparison.Ordinal))
            translated = TranslateUsingMap(value, AdditionalMap(code));
        return TranslateCountUnits(translated, code);
    }

    public static bool TryNormalizeToEnglish(string language, string value, out string english)
    {
        string code = NormalizeLanguage(language);
        Dictionary<string, string> reverse = code switch { "zh-CN" => ChineseReverse, "pt-BR" => PortugueseReverse, "it" => ItalianReverse, _ => new Dictionary<string, string>() };
        if (reverse.TryGetValue(value, out english!)) return true;
        if (TryNormalizeFromMap(value, Map(code), code, out english)) return true;
        var additional = AdditionalMap(code);
        if (AdditionalReverseMap(code).TryGetValue(value, out english!)) return true;
        if (TryNormalizeFromMap(value, additional, code, out english)) return true;
        english = value;
        return false;
    }

    private static bool TryNormalizeFromMap(string value, Dictionary<string, string> map, string language, out string english)
    {
        foreach (var pair in map.Where(pair => pair.Key.EndsWith(" ", StringComparison.Ordinal)).OrderByDescending(pair => pair.Value.Length))
        {
            if (!value.StartsWith(pair.Value, StringComparison.Ordinal)) continue;
            english = pair.Key + NormalizeCountUnits(value[pair.Value.Length..], language);
            return true;
        }
        english = value;
        return false;
    }

    public static bool TryNormalizeRussianToEnglish(string value, out string english)
        => AdditionalRussianToEnglish.TryGetValue(value, out english!) || TryNormalizeRussianPrefix(value, out english);

    private static bool TryNormalizeRussianPrefix(string value, out string english)
    {
        foreach (var pair in AdditionalRussianToEnglish.Where(pair => pair.Key.EndsWith(" ", StringComparison.Ordinal)).OrderByDescending(pair => pair.Key.Length))
        {
            if (!value.StartsWith(pair.Key, StringComparison.Ordinal)) continue;
            english = pair.Value + value[pair.Key.Length..];
            return true;
        }
        english = value;
        return false;
    }

    private static Dictionary<string, string> Map(string language)
        => language switch { "zh-CN" => Chinese, "pt-BR" => Portuguese, "it" => Italian, _ => new Dictionary<string, string>() };

    private static string TranslateCountUnits(string value, string language)
        => language switch
        {
            "zh-CN" => value.Replace(" blocks", " 个区块", StringComparison.Ordinal).Replace(" block", " 个区块", StringComparison.Ordinal),
            "pt-BR" => value.Replace(" blocks", " blocos", StringComparison.Ordinal).Replace(" block", " bloco", StringComparison.Ordinal),
            "it" => value.Replace(" blocks", " blocchi", StringComparison.Ordinal).Replace(" block", " blocco", StringComparison.Ordinal),
            _ => value
        };

    private static string NormalizeCountUnits(string value, string language)
        => language switch
        {
            "zh-CN" => value.Replace(" 个区块", " blocks", StringComparison.Ordinal),
            "pt-BR" => value.Replace(" blocos", " blocks", StringComparison.Ordinal).Replace(" bloco", " block", StringComparison.Ordinal),
            "it" => value.Replace(" blocchi", " blocks", StringComparison.Ordinal).Replace(" blocco", " block", StringComparison.Ordinal),
            _ => value
        };

    private static string TranslateUsingMap(string value, Dictionary<string, string> map)
    {
        if (map.TryGetValue(value, out string? exact)) return exact;
        return TryTranslatePrefix(value, map, out string translated) ? translated : value;
    }

    private static bool TryTranslatePrefix(string value, Dictionary<string, string> map, out string translated)
    {
        foreach (var pair in map.Where(pair => pair.Key.EndsWith(" ", StringComparison.Ordinal)).OrderByDescending(pair => pair.Key.Length))
        {
            if (!value.StartsWith(pair.Key, StringComparison.Ordinal)) continue;
            translated = pair.Value + value[pair.Key.Length..];
            return true;
        }
        translated = value;
        return false;
    }

    private static Dictionary<string, string> Reverse(Dictionary<string, string> map)
        => map.GroupBy(pair => pair.Value, StringComparer.Ordinal).ToDictionary(group => group.Key, group => group.First().Key, StringComparer.Ordinal);
